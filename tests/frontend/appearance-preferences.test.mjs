import {readFile} from 'node:fs/promises';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=await readFile(new URL('../../js/app.js',import.meta.url),'utf8');
const theme=source.slice(source.indexOf('let appearanceUserId'),source.indexOf('/** 2.1 · Íconos'));
const menu=source.slice(source.indexOf('const MENU_LAYOUT_KEY'),source.indexOf('/** Familia elegida'));
const values=new Map();
const context=vm.createContext({document:{documentElement:{dataset:{}}},localStorage:{getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v)}});
vm.runInContext(theme+'\n'+menu,context);
const run=s=>vm.runInContext(s,context);
run("appearanceUserId='doctor-a';setMenuLayout('horizontal');applyTheme('light')");
assert.equal(run('getMenuLayout()'),'horizontal');
assert.equal(run('getTheme()'),'light');
run("appearanceUserId='doctor-b'");
assert.equal(run('getMenuLayout()'),'lateral');
assert.equal(run('getTheme()'),'sistema');
run("setMenuLayout('lateral');applyTheme('dark');appearanceUserId='doctor-a'");
assert.equal(run('getMenuLayout()'),'horizontal');
assert.equal(run('getTheme()'),'light');
run("localStorage={getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}}");
assert.equal(run('getMenuLayout()'),'lateral');
assert.equal(run('getTheme()'),'sistema');
run("applyTheme('light');setMenuLayout('horizontal')");
assert.equal(context.document.documentElement.dataset.theme,'light');
values.set('sofa.tema.doctor-a','emerald');
context.localStorage={getItem:k=>values.get(k)||null,setItem:(k,v)=>values.set(k,v)};
assert.equal(run('getTheme()'),'sistema');
assert.equal(run('Object.keys(THEMES).length'),3);
const permissionsSource=await readFile(new URL('../../js/utils/permissions.js',import.meta.url),'utf8');
const {FAMILIAS_ROL}=await import('data:text/javascript;base64,'+Buffer.from(permissionsSource).toString('base64'));
const groups=FAMILIAS_ROL.client;
assert.ok(groups.find(g=>g.group==='Historia clínica').routes.includes('historia-clinica'));
assert.equal(groups.flatMap(g=>g.routes).filter(r=>r==='historia-clinica').length,1);
assert.ok(groups.find(g=>g.group==='Mi dinero').routes.includes('mi-dinero'));
console.log('PASS: preferencias independientes por usuario, persistencia, almacenamiento bloqueado y navegación clínica sin duplicados.');
